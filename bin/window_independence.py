#!/usr/bin/env python3
"""TWO FOOTPRINTS FROM ONE CASE: are they two samples, or one sample written twice?

WHY A CASE PRODUCES TWO. Re-running an identical case -- same restart, same forcing, same
rotation, same code -- gave integral 1.463 -> 1.019 and array share 5.65% -> 1.07%. That is
turbulence REALISATION variance, and every error floor this project quotes is measured
WITHIN one realisation and is therefore too small. Repeating whole cases would price that
at a full spin-up each; a second 2700 s window on the same run prices it at 0.75 h, taking
a case from 1.25 h per footprint to 1.0.

That trade is only worth making if the second window is actually a second draw, and this
script is what decides it. TWO SEPARATE QUESTIONS, and they have different consequences:

  (a) ARE THE TWO WINDOWS INDEPENDENT?  The decorrelation time was measured at dx = 16 m
      with a 10 m receptor. At 30 m in a 3660 m box the footprints are larger and the
      transit times longer, so it may now exceed the 30-minute averaging period -- in which
      case the second footprint is a near-duplicate and the extra 0.75 h is WASTED. Scored
      two ways that fail differently: the release groups' own lagged autocorrelation, which
      estimates the decorrelation time from this case rather than inheriting it; and the
      direct difference |w0 - w1| against the WITHIN-window half-vs-half floor, which
      should be about floor*sqrt(2) for two independent draws and about zero for a
      duplicate.

  (b) HOW FAR DOES z_i DRIFT BETWEEN THEM?  Small drift means near-replicates at one
      condition, which is what addresses realisation noise. Large drift means two DIFFERENT
      conditions -- still valuable as corpus coverage, but it does NOT reduce noise at a
      fixed condition, and the corpus would still owe averaging within condition bins. The
      drift is reported both raw and translated through Kljun's z_m/h channel, because a
      z_i change only matters to the extent it moves the footprint.

WHAT IS NOT ASSUMED. The independence verdict is scored against this case's own floors, not
against a constant: the half-vs-half difference inside each window, and the standard error
of the array share over its release groups. Where the two windows differ by less than the
floor, the honest verdict is NEAR-DUPLICATE; where they differ by more, the second window
is carrying information. A tolerance picked in advance would be the error this project's
conventions section exists to prevent.

usage: window_independence.py <w0.json> <w1.json> [--out results/window_independence.txt]
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lpdm import kljun


def group_series(d, name="solar array"):
    """Per-release-group share of one cover class, in release order."""
    g = d.get("cover_share_halves") or []
    return np.array([float(r.get(name, np.nan)) for r in g], dtype=float)


def lag_corr(x, k):
    x = np.asarray(x, float)
    x = x[np.isfinite(x)]
    if len(x) <= k + 2:
        return np.nan
    a, b = x[:-k] if k else x, x[k:] if k else x
    a = a - a.mean(); b = b - b.mean()
    den = np.sqrt((a * a).sum() * (b * b).sum())
    return float((a * b).sum() / den) if den > 0 else np.nan


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("w0")
    ap.add_argument("w1")
    ap.add_argument("--cover", default="solar array")
    ap.add_argument("--out", default="results/window_independence.txt")
    a = ap.parse_args()
    d0, d1 = json.load(open(a.w0)), json.load(open(a.w1))

    lines = []
    P = lambda s="": (print(s), lines.append(s))
    P("TWO FOOTPRINTS FROM ONE CASE.  Generated by bin/window_independence.py.")
    P("")
    P(f"  w0 {os.path.basename(a.w0)}")
    P(f"  w1 {os.path.basename(a.w1)}")
    s0, s1 = d0.get("stats", {}), d1.get("stats", {})
    l0, l1 = d0.get("les", {}), d1.get("les", {})
    rel = float(d0.get("rel_seconds") or 1800.0)
    P("")

    # ---- (b) first: what condition is each window at? -------------------------------
    P("=== (b) IS IT THE SAME CONDITION?  the two windows' own LES-read inputs ===")
    P(f"  {'input':<14}{'w0':>12}{'w1':>12}{'change':>12}{'relative':>11}")
    for k, unit in (("h", "m"), ("ustar", "m/s"), ("L", "m"), ("u_mean", "m/s"),
                    ("wdir", "deg"), ("sigma_v", "m/s"), ("sigma_w", "m/s"),
                    ("htFlux", "K m/s")):
        v0, v1 = s0.get(k), s1.get(k)
        if not isinstance(v0, (int, float)) or not isinstance(v1, (int, float)):
            continue
        rl = (v1 - v0) / abs(v0) if v0 else np.nan
        P(f"  {k:<14}{v0:12.4f}{v1:12.4f}{v1-v0:+12.4f}{100*rl:+10.1f}%")
    dh = (s1.get("h", np.nan) - s0.get("h", np.nan))
    P(f"  z_i drift {dh:+.0f} m over {rel/3600:.2f} h of separation "
      f"= {dh/(rel/3600):+.0f} m/h")

    # ...and how much of that reaches the footprint, which is the only part that matters
    try:
        zm = float(d0.get("zm_agl") or d0.get("zm"))
        xp, x9 = [], []
        for s in (s0, s1):
            xp.append(kljun.peak_distance(zm, float(s["h"]), float(s["ustar"]),
                                          umean=float(s["u_mean"]), L=float(s["L"])))
            fy, xs = kljun.crosswind_integrated(
                np.linspace(1.0, 6000.0, 3000), zm, float(s["h"]), float(s["ustar"]),
                umean=float(s["u_mean"]), L=float(s["L"]))
            c = np.cumsum(fy); c /= c[-1]
            x9.append(float(xs[np.searchsorted(c, 0.90)]))
        P("")
        P("  translated through Kljun, which is the only part of a z_i change that reaches")
        P("  a footprint (its channel is 1/(1 - z_m/h), ~3x stronger at 30 m than at 10 m):")
        P(f"  {'Kljun':<14}{'w0':>12}{'w1':>12}{'change':>12}")
        P(f"  {'x_peak (m)':<14}{xp[0]:12.0f}{xp[1]:12.0f}{xp[1]-xp[0]:+12.0f}")
        P(f"  {'x90 (m)':<14}{x9[0]:12.0f}{x9[1]:12.0f}{x9[1]-x9[0]:+12.0f}")
    except Exception as e:                       # never let the report die on a missing key
        P(f"  (Kljun translation unavailable: {e})")

    # ---- (a) independence ------------------------------------------------------------
    P("")
    P("=== (a) ARE THEY INDEPENDENT?  |w0 - w1| against each window's OWN floor ===")
    h0, h1 = d0.get("halves", {}), d1.get("halves", {})
    P("  The floor is the half-vs-half difference INSIDE a window -- one degree of freedom,")
    P("  so it is a floor and not a distribution; the larger of the two is used, as the")
    P("  deciding test does. Two INDEPENDENT draws should differ by about floor*sqrt(2);")
    P("  a near-duplicate by about zero.")
    P("")
    P(f"  {'observable':<16}{'w0':>11}{'w1':>11}{'|diff|':>10}{'floor':>10}{'ratio':>9}  verdict")
    rows = [("peak_x", "peak_x", "dpeak"), ("centroid_dist", "centroid_dist", "dcentroid"),
            ("x80", "x80", "dx80")]
    ratios = []
    for label, lk, hk in rows:
        v0, v1 = l0.get(lk), l1.get(lk)
        fl = max(abs(float(h0.get(hk, np.nan) or 0.0)), abs(float(h1.get(hk, np.nan) or 0.0)))
        if not isinstance(v0, (int, float)) or not isinstance(v1, (int, float)):
            continue
        dv = abs(v1 - v0)
        r = dv / fl if fl > 0 else np.nan
        ratios.append(r)
        vd = ("NO FLOOR" if not (fl > 0) else
              "near-duplicate" if r < 0.5 else
              "independent-scale" if r >= 1.0 else "partial")
        P(f"  {label:<16}{v0:11.1f}{v1:11.1f}{dv:10.1f}{fl:10.1f}{r:9.2f}  {vd}")

    # the array share, scored against the SE of its own release groups rather than a
    # half-vs-half difference -- a share is what Gate F leans on and it has N groups
    g0, g1 = group_series(d0, a.cover), group_series(d1, a.cover)
    if g0.size and g1.size:
        se = np.sqrt(np.nanvar(g0, ddof=1) / max(g0.size, 1)
                     + np.nanvar(g1, ddof=1) / max(g1.size, 1))
        m0, m1 = np.nanmean(g0), np.nanmean(g1)
        r = abs(m1 - m0) / se if se > 0 else np.nan
        ratios.append(r)
        P(f"  {a.cover:<16}{100*m0:10.2f}%{100*m1:10.2f}%{100*abs(m1-m0):9.2f}%"
          f"{100*se:9.2f}%{r:9.2f}  {'differ' if r >= 3 else 'inside 3 SE'}")
        P(f"    ({g0.size} + {g1.size} release groups; the SE is of the DIFFERENCE)")

        # ---- the decorrelation ladder, read off this case ---------------------------
        both = np.concatenate([g0, g1])
        step = rel / max(g0.size, 1)
        P("")
        P("  the release groups' own lagged autocorrelation, which estimates the")
        P(f"  decorrelation time FROM THIS CASE rather than inheriting the 16 m / 10 m")
        P(f"  table ({both.size} groups, {step:.0f} s apart):")
        P(f"  {'lag':>5}{'seconds':>10}{'r':>9}")
        indep = None
        for k in range(1, min(9, both.size - 2)):
            r_ = lag_corr(both, k)
            P(f"  {k:5d}{k*step:10.0f}{r_:9.2f}")
            if indep is None and np.isfinite(r_) and abs(r_) < 2.0 / np.sqrt(both.size):
                indep = k * step
        thr = 2.0 / np.sqrt(both.size)
        P(f"  independence threshold |r| < 2/sqrt(n) = {thr:.2f}; first lag inside it: "
          f"{('%.0f s' % indep) if indep else 'none in range'}")
        if indep is not None:
            P(f"  the two windows' release periods are {rel:.0f} s apart at their nearest,")
            P(f"  so {'they clear' if indep <= rel else 'they DO NOT clear'} that timescale.")

    # ---- the verdict ------------------------------------------------------------------
    P("")
    P("=== WHAT FOLLOWS ===")
    good = [r for r in ratios if np.isfinite(r)]
    med = float(np.median(good)) if good else np.nan
    if not good:
        P("  NO VERDICT: no observable had a usable floor.")
    elif med < 0.5:
        P(f"  NEAR-DUPLICATE (median |diff|/floor {med:.2f}). The second window is not a")
        P("  second draw, and the extra 0.75 h per case buys little -- say so plainly and")
        P("  price a case at one footprint again.")
    else:
        P(f"  A SECOND DRAW (median |diff|/floor {med:.2f}). The second window carries")
        P("  information the first does not, so the pair prices realisation spread at")
        P("  0.75 h instead of a whole case.")
    if np.isfinite(dh):
        P("")
        if abs(dh) < 50:
            P(f"  AND IT IS THE SAME CONDITION (z_i moved {dh:+.0f} m), so the pair is a")
            P("  replicate at one point in input space and DOES reduce realisation noise")
            P("  there.")
        else:
            P(f"  BUT IT IS A DIFFERENT CONDITION (z_i moved {dh:+.0f} m), so the pair is")
            P("  COVERAGE rather than replication: it does not reduce noise at a fixed")
            P("  condition, and the corpus still owes averaging within condition bins.")
    if a.out:
        os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
        open(a.out, "w").write("\n".join(lines) + "\n")
        print(f"\n  wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

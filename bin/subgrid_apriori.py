#!/usr/bin/env python3
"""A PRIORI: how much resolved sigma_w^2 at the receptor would a COARSER dx keep?

WHY THIS EXISTS. The seventh pass moved the receptor from 10 m to 30 m because at
z/Delta ~ 1 the near field was closure output rather than LES output: ~90% of sigma_w^2 at
the receptor was sub-grid. At 24 m that became 52.5% convective / 86.4% neutral, MEASURED.
Widening the box to 3660 m by coarsening to dx = 30 m lowers z/Delta from 1.76 to 1.52 --
back TOWARD the regime the pass exists to escape -- and the standing rule is that this
number is re-measured at every grid and never carried.

Normally re-measuring costs a seed and a window. It does not have to. The variance a
dx = 30 m grid could not resolve is, to leading order, the variance that already sits at
horizontal scales below its Nyquist -- and that is readable off the 24 m fields ALREADY ON
DISK, with no GPU at all. This is the standard a priori LES filter test: take the 2-D
spectrum of w on the receptor level, and integrate it above and below the coarser grid's
cutoff.

WHAT IT DOES AND DOES NOT SAY. It bounds the RESOLVED side only: a coarser run does not
merely lose the small scales, it also produces different large ones, and its sub-grid model
returns some of what was lost. So read the output as "the resolved variance falls by at
least this much", i.e. a LOWER bound on the degradation, not a prediction of the new
sub-grid fraction. That is the direction that matters here, because the question being
asked is whether coarsening is safe.

usage: subgrid_apriori.py <window-dir> --k 3 --dx 24 --to 30 [--to 36 ...]
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

import numpy as np
from netCDF4 import Dataset


def w_plane(path, k):
    with Dataset(path) as nc:
        v = nc.variables["w"]
        a = np.asarray(v[:], dtype=np.float64)
    a = np.squeeze(a)
    if a.ndim != 3:
        raise SystemExit(f"{path}: w has shape {a.shape}, expected 3-D")
    # FastEddy writes (x, y, z); the LPDM cache transposes. Take the z axis as the one
    # matching the vertical extent, which is unambiguous on a 122^3 grid only if we look
    # at the file's own dimension order.
    return a


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("windir")
    ap.add_argument("--k", type=int, default=3, help="receptor level index")
    ap.add_argument("--dx", type=float, default=24.0, help="the spacing of THESE fields")
    ap.add_argument("--to", type=float, action="append", default=None,
                    help="candidate coarser spacing (repeatable)")
    ap.add_argument("--ndump", type=int, default=40, help="dumps to average over")
    ap.add_argument("--filter-factors", default="2,4,6",
                    help="effective LES filter cutoff in units of dx. 2 is the bare "
                         "Nyquist; a real LES's numerics damp well above it, and 4-6 dx "
                         "is the usual measured effective width, so the honest answer is "
                         "a range rather than one number.")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    to = a.to or [30.0, 36.0]

    paths = sorted(glob.glob(os.path.join(a.windir, "*.[0-9]*")),
                   key=lambda p: int(p.rsplit(".", 1)[1]))
    if not paths:
        raise SystemExit(f"no dumps in {a.windir}")
    # ONE RUN PER DIRECTORY: filter on the single base name (PROJECT_BRIEF.md / TRAPS 18c).
    bases = {os.path.basename(p).rsplit(".", 1)[0] for p in paths}
    if len(bases) != 1:
        raise SystemExit(f"{a.windir} holds {len(bases)} run families: {sorted(bases)}")
    sel = paths[:: max(1, len(paths) // a.ndump)][: a.ndump]

    lines = []
    P = lambda s="": (print(s), lines.append(s))
    P("A PRIORI RESOLVED-VARIANCE TEST.  Generated by bin/subgrid_apriori.py.")
    P("")
    P(f"  fields   {a.windir}  ({len(sel)} of {len(paths)} dumps)")
    P(f"  spacing  dx = {a.dx:g} m, receptor level k = {a.k}")
    P("")
    P("  The 2-D spectrum of w on the receptor level, split at each candidate grid's")
    P("  Nyquist.  'kept' is the fraction of the RESOLVED variance that survives; the")
    P("  rest moves to the sub-grid model.  This bounds the resolved side only -- a")
    P("  coarser run also makes different large scales -- so it is a LOWER bound on the")
    P("  degradation, which is the conservative direction for a go/no-go.")
    P("")

    acc = None
    n = 0
    for p in sel:
        with Dataset(p) as nc:
            v = nc.variables["w"]
            dims = v.dimensions
            idx = [slice(None)] * len(dims)
            zi = [i for i, d in enumerate(dims) if "z" in d.lower()]
            if not zi:
                raise SystemExit(f"cannot find a z dimension in {dims}")
            idx[zi[0]] = a.k
            w = np.asarray(v[tuple(idx)], dtype=np.float64)
        w = np.squeeze(w)
        if w.ndim != 2:
            raise SystemExit(f"{p}: receptor plane is {w.shape}, expected 2-D")
        if not np.isfinite(w).all():
            raise SystemExit(f"{p}: non-finite w on the receptor plane")
        w = w - w.mean()
        F = np.fft.fft2(w)
        P2 = (np.abs(F) ** 2) / (w.size ** 2)      # variance per mode, sums to var(w)
        acc = P2 if acc is None else acc + P2
        n += 1
    P2 = acc / n
    ny, nx = P2.shape
    kx = np.fft.fftfreq(nx, d=a.dx)                # cycles per metre
    ky = np.fft.fftfreq(ny, d=a.dx)
    KX, KY = np.meshgrid(kx, ky, indexing="xy")
    kmag = np.hypot(KX, KY)
    tot = P2.sum()
    P(f"  resolved sigma_w^2 on this grid = {tot:.6f} m2/s2  (sigma_w = {np.sqrt(tot):.4f} m/s)")
    P("")
    facs = [float(x) for x in a.filter_factors.split(",")]
    P("  " + f"{'to dx':>7}{'Delta':>8}{'z/Delta':>9}" +
      "".join(f"{('kept @%gdx' % f):>13}" for f in facs))
    for d2 in [a.dx] + list(to):
        Delta = (d2 * d2 * 8.5583) ** (1.0 / 3.0)
        row = f"  {d2:7.0f}{Delta:8.2f}{30.0/Delta:9.2f}"
        for f in facs:
            # a cutoff at wavelength f*d2 is a wavenumber 1/(f*d2); the SAME physical
            # cutoff is applied to the reference row, so the reference reads 100% only
            # where f*dx is inside this grid's own Nyquist.
            keep = P2[kmag <= 1.0 / (f * d2)].sum()
            row += f"{100*keep/tot:12.1f}%"
        P(row)
    P("")
    P("  READ IT LIKE THIS. If a candidate keeps X% of the resolved variance, and this")
    P("  grid measured a resolved fraction R, the candidate's resolved fraction is AT")
    P("  MOST R*X (its sub-grid model will not give back more than the filter removed,")
    P("  and its own large scales will differ).")
    if a.out:
        os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
        open(a.out, "w").write("\n".join(lines) + "\n")
        print(f"\n  wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

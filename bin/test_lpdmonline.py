#!/usr/bin/env python3
"""PRODUCER vs CONSUMER: does the LES stage exactly what it writes?

THE ONE THING NO CPU TEST COULD COVER. `bin/test_dumpsrc.py` proves the readers do not care
which source they read from, and `bin/test_ringsrc.py` proves the consumer transports a
snapshot without changing it -- but both fabricate the staged files from netCDF dumps, so
both are scoring code on THIS side of the interface. Whether FastEddy writes what
`lpdm/ringsrc.py` expects can only be answered by a real LES, and it is the half where a
transpose, a rho division or a field-order slip would live.

`lpdmOnlineSelector = 2` is what makes the question answerable: the LES stages AND writes,
from the SAME `ioBuffField` at the same point in the writer. So the two artifacts should be
identical, and the comparison is EXACT -- not a tolerance. There is no arithmetic between
them. (Run with `ioLPDMmode = 0` so the netCDF side is full fp32; under lean output the
3-D prognostics are CF-packed to 16 bit and the comparison would be against the packing
rather than against the hand-off.)

WHAT AN EXACT MATCH RULES OUT, which is the point of listing it: a wrong field order in
meta.txt, a kji-vs-ijk transpose, a snapshot staged before the rho division, an off-by-one
in the ring slot, a 2-D field read with 3-D extents, and a truncated write. What it does
NOT cover is the pause/resume handshake and the queue backpressure, which
`bin/test_ringsrc.py` exercises and which have no LES-side arithmetic in them.

THE CONSUMER USED HERE IS THE PRODUCTION ONE. lpdm/ringsrc.py, not a reimplementation of
the format -- a second parser agreeing with the first would say nothing about the producer.

usage: test_lpdmonline.py <staging-dir> <netcdf-dir> [--base FE_ACC]
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np
from netCDF4 import Dataset

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lpdm.fields import FieldSet, dump_series
from lpdm.les_stats import window_stats
from lpdm.ringsrc import RingConsumer


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stagedir")
    ap.add_argument("ncdir")
    ap.add_argument("--k", type=float, default=3.0)
    ap.add_argument("--out", default="results/lpdmonline_acceptance.txt")
    a = ap.parse_args()

    lines = []
    P = lambda s="": (print(s), lines.append(s))
    P("PRODUCER vs CONSUMER: the in-process hand-off against the file it also wrote.")
    P("  Generated by bin/test_lpdmonline.py, from ONE LES run at lpdmOnlineSelector = 2.")
    P("")

    rc = RingConsumer(a.stagedir, verbose=False)
    m = rc.meta
    P(f"  staged  {a.stagedir}")
    P(f"  written {a.ncdir}")
    P(f"  format  {m.nx}x{m.ny}x{m.nz}, dt {m.dt:g}, selector {m.selector}, "
      f"{m.snap_bytes/1e6:.1f} MB/snapshot")
    P(f"  3-D {m.fields3}")
    P(f"  2-D {m.fields2}")
    P("")

    # KEEP the staged files: this is a comparison, not a consumption. The queue depth was
    # set high enough for the whole run so the producer never blocked on the backlog.
    handles, pause = rc.drain_until_pause(keep=True)
    ncs = dump_series(a.ncdir)
    P(f"  {len(handles)} snapshots staged, {len(ncs)} dumps written")
    fails = 0

    steps_h = [h.step for h in handles]
    steps_n = [int(p.rsplit(".", 1)[1]) for p in ncs]
    common = sorted(set(steps_h) & set(steps_n))
    ok = len(common) == len(handles) == len(ncs)
    P(f"  [{'ok  ' if ok else 'FAIL'}] the two series carry the same steps "
      f"({len(common)} in common)")
    if not ok:
        P(f"        staged only:  {sorted(set(steps_h) - set(steps_n))[:6]}")
        P(f"        written only: {sorted(set(steps_n) - set(steps_h))[:6]}")
    fails += (not ok)

    # ---- field by field, exactly ------------------------------------------------------
    P("")
    P("  EXACT equality, field by field. Both come from the same ioBuffField at the same")
    P("  point in the writer, so any difference at all is the hand-off.")
    P("")
    P(f"  {'field':<12}{'kind':>6}{'max |diff|':>14}{'n differ':>11}  verdict")
    by_step = {h.step: h for h in handles}
    worst = {}
    for p in ncs:
        s = int(p.rsplit(".", 1)[1])
        h = by_step.get(s)
        if h is None:
            continue
        with Dataset(p) as ds:
            for nm in list(m.fields3) + list(m.fields2):
                if nm not in ds.variables:
                    worst.setdefault(nm, ["MISSING", 0.0, 0])
                    continue
                ref = np.squeeze(np.asarray(ds[nm][:], dtype=np.float32))
                got = np.asarray(h[nm], dtype=np.float32)
                if ref.shape != got.shape:
                    worst[nm] = ["SHAPE %s vs %s" % (ref.shape, got.shape), np.nan, -1]
                    continue
                d = np.abs(ref.astype(np.float64) - got.astype(np.float64))
                nd = int((ref != got).sum())
                cur = worst.setdefault(nm, ["", 0.0, 0])
                cur[1] = max(cur[1], float(d.max()))
                cur[2] += nd
    for nm in list(m.fields3) + list(m.fields2):
        kind = "3-D" if nm in m.fields3 else "2-D"
        st, mx, nd = worst.get(nm, ["NOT COMPARED", np.nan, -1])
        good = (st == "") and nd == 0
        fails += (not good)
        P(f"  {nm:<12}{kind:>6}{mx:14.3e}{nd:11d}  "
          f"{'ok' if good else (st or 'DIFFERS')}")

    # ---- and the quantity every gate is built on --------------------------------------
    P("")
    P("  window_stats through both sources -- the check that catches a slot-ordering or")
    P("  rho-division slip even when the per-field maxima look small.")
    sa, sb = window_stats(ncs, a.k), window_stats(handles, a.k)
    bad = []
    for k in sorted(set(sa) | set(sb)):
        va, vb = sa.get(k), sb.get(k)
        if isinstance(va, np.ndarray) or isinstance(vb, np.ndarray):
            same = va is not None and vb is not None and np.array_equal(va, vb)
        else:
            same = (va == vb) or (va != va and vb != vb)
        if not same:
            bad.append((k, va, vb))
    P(f"  [{'ok  ' if not bad else 'FAIL'}] window_stats: {len(sa)} keys, {len(bad)} differ")
    for k, va, vb in bad[:8]:
        P(f"        {k}: written {va!r}  staged {vb!r}")
    fails += bool(bad)

    fa, fb = FieldSet(ncs, m.dt, verbose=False), FieldSet(handles, m.dt, verbose=False)
    bad = [nm for nm in ("t", "zk", "zg", "zg_dx", "zg_dy", "u", "v", "w", "e", "eps",
                         "dsig2dz", "ustar", "z0m")
           if not np.array_equal(np.asarray(getattr(fa, nm)), np.asarray(getattr(fb, nm)))]
    P(f"  [{'ok  ' if not bad else 'FAIL'}] FieldSet: {len(bad)} attributes differ"
      + (f" ({bad})" if bad else ""))
    fails += bool(bad)

    P("")
    P(f"  {fails} failure(s)")
    if fails == 0:
        P("  The LES stages exactly what it writes. A wrong field order, a kji/ijk")
        P("  transpose, a pre-rho-division snapshot, an off-by-one ring slot, a 2-D field")
        P("  read with 3-D extents and a truncated write are all excluded.")
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w").write("\n".join(lines) + "\n")
    print(f"\n  wrote {a.out}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
